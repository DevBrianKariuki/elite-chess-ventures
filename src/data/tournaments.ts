// Helper function to get visible tournaments
export const getVisibleTournaments = () => {
    return tournaments.filter(t => t.isVisible !== false);
};

// Helper function to get featured tournaments
export const getFeaturedTournaments = () => {
    return tournaments.filter(t => t.isFeatured === true && t.isVisible !== false);
};

// Helper function to get upcoming tournaments (open or upcoming status)
export const getUpcomingTournaments = () => {
    return tournaments.filter(t =>
        (t.status === 'open' || t.status === 'upcoming') &&
        t.isVisible !== false
    );
};
